export function mapMunicipalityName(jsonName: string): string {
  const normalized = jsonName.trim();
  
  const mapping: Record<string, string> = {
    'Городской округ город Тула': 'г. Тула',
    'Городской округ город Алексин': 'г. Алексин',
    'Городской округ город Ефремов': 'г. Ефремов',
    'Городской округ город Донской': 'г. Донской',
    'Городской округ город Щёкино': 'г. Щёкино',
    'Городской округ город Новомосковск': 'г. Новомосковск',
    'Каменский муниципальный район': 'Каменский район',
    'Воловский муниципальный район': 'Воловский район',
    'Кимовский муниципальный район': 'Кимовский район',
    'Заокский муниципальный район': 'Заокский район',
    'Чернский муниципальный район': 'Чернский район',
    'Тепло-Огаревский муниципальный район': 'Тепло-Огаревский район',
    'Богородицкий муниципальный район': 'Богородицкий район',
    'Веневский муниципальный район': 'Веневский район',
    'Узловский муниципальный район': 'Узловский район',
    'Щекинский муниципальный район': 'Щекинский район',
    'Городской округ рабочий поселок Новогуровский': 'р.п. Новогуровский',
  };

  if (mapping[normalized]) {
    return mapping[normalized];
  }

  for (const [json, api] of Object.entries(mapping)) {
    if (normalized.toLowerCase().includes(json.toLowerCase()) || 
        json.toLowerCase().includes(normalized.toLowerCase())) {
      return api;
    }
  }

  let result = normalized
    .replace(/Городской округ город/gi, 'г.')
    .replace(/Городской округ/gi, '')
    .replace(/муниципальный район/gi, 'район')
    .replace(/рабочий поселок/gi, 'р.п.')
    .replace(/\s+/g, ' ')
    .trim();

  return result;
}

